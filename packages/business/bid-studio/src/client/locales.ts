/**
 * Localize a workflow driver while preserving unknown definition values.
 * @param driver - driver recorded in the ontology definition.
 * @param t - workbench translator.
 * @returns localized driver label.
 */
export function driverLabel(driver: string, t: PropsLocale<'bidStudio'>['t']): string {
  switch (driver) {
    case 'machine': return t('driver.machine')
    case 'workflow': return t('driver.workflow')
    case 'agent': return t('driver.agent')
    case 'human': return t('driver.human')
    default: return driver
  }
}
